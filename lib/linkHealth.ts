// Здоровье ссылки на программу (url_status/url_checked_at, см.
// sql/2026-09-08-tuition-truth.sql и scripts/check-links.mjs). Первый
// полный прогон 2026-09-08 нашёл 348 из 1405 битых ссылок (25%) — пока
// они не заменены (это отдельная исследовательская задача, не быстрый
// фикс), интерфейс не должен вести пользователя на мёртвую страницу
// без предупреждения.
// ВАЖНО про 403 (найдено 2026-09-07): 403 — это НЕ мёртвая ссылка.
// Так отвечают сайты вузов с защитой от ботов (Cloudflare и подобные):
// живому человеку в браузере страница открывается нормально, а нашему
// скрипту — нет. verifyUrl() в scripts/research-programs.mjs с самого
// начала считает 403 успехом ("OK (403)" в логах сбора) и оставляет
// такие программы в базе — а здесь тот же 403 считался битой ссылкой.
// Из-за этого рассинхрона 94 программы с рабочими страницами показывали
// студенту ложное предупреждение "ссылка не работает".
//
// Мёртвым считаем то, где страницы действительно нет (404/410), либо
// запрос вообще не дошёл (0 или отрицательный код от check-links.mjs).
// 5xx намеренно НЕ считаем мёртвым — это временный сбой сервера вуза,
// а не пропавшая программа; при следующем прогоне cron'а код обновится.
export function isDeadLink(urlStatus: number | null | undefined): boolean {
  if (urlStatus == null) return false
  if (urlStatus <= 0) return true
  return urlStatus === 404 || urlStatus === 410
}
