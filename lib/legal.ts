/** Есть ли гайд хотя бы по одной из выбранных пользователем стран. */
export function hasGuideCoverage(countries: string[] | undefined | null): boolean {
  if (!countries?.length) return false
  return countries.some(c => (GUIDE_COUNTRIES as readonly string[]).includes(c))
}
