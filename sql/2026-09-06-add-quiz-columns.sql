-- Квиз "что тебе важнее" (Куда хочешь поехать → "Не знаю куда хочу — помоги
-- выбрать") задаёт 4 реальных вопроса (деньги/остаться в Европе/язык/среда)
-- и использует ответы, чтобы подобрать топ-3 страны. Но ответы никогда не
-- сохранялись в profiles — таких колонок не было вообще. При этом
-- app/api/verdict/route.ts читает profile.quiz_vibe/quiz_stay и при
-- отсутствии подставляет дефолт ('качество жизни', 'не решил') ВСЕМ без
-- исключения — ИИ-анализ утверждал "это совпадает с твоим приоритетом",
-- хотя пользователь никогда такого не говорил. Добавляем колонки, чтобы
-- анкета могла реально их сохранить (см. buildProfilePayload в app/page.tsx)
-- и дефолт в промпте перестал быть ложью для всех, кто квиз проходил.
--
-- НЕ применено в Supabase — выполнить вручную через SQL Editor (тот же
-- паттерн, что у is_pro, см. sql/2026-08-31-add-is-pro-column.sql).

alter table profiles
  add column if not exists quiz_cost text,
  add column if not exists quiz_stay text,
  add column if not exists quiz_lang text,
  add column if not exists quiz_vibe text;
